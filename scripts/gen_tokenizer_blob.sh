#!/usr/bin/env bash
# Regenerate src/llm/tok512_blob.h from the canonical tokenizer binary.
# EMBED_FILES in ESP-IDF/PlatformIO is fragile here, so the tokenizer is
# compiled in as a plain byte array instead.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/src/llm/tok512.bin"
OUT="$ROOT/src/llm/tok512_blob.h"

[[ -f "$SRC" ]] || { echo "missing $SRC" >&2; exit 1; }

{
    echo "/* Generated by scripts/gen_tokenizer_blob.sh from src/llm/tok512.bin. */"
    echo "#pragma once"
    # Run from the file's directory: older xxd has no -n, and -i derives the
    # variable name from the file name given on the command line.
    ( cd "$(dirname "$SRC")" && xxd -i "$(basename "$SRC")" ) |
        sed -e 's/^unsigned char/static const unsigned char/' \
            -e 's/^unsigned int/static const unsigned int/'
} >"$OUT"

echo "wrote $OUT ($(stat -c %s "$OUT") bytes)"
